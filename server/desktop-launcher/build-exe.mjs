import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const SERVER_DIR = path.resolve(__dirname, "..");
const PROJECT_ROOT = path.resolve(SERVER_DIR, "..");

const CS_SOURCE = path.join(__dirname, "PurrCamLauncher.cs");
const LOCAL_BUILD_CONFIG_CS = path.join(__dirname, "BuildConfig.cs");
const ICO_PATH = path.join(__dirname, "purrcam.ico");

function getHostLeakTokens() {
  const tokens = new Set();
  try {
    const user = os.userInfo().username;
    if (user && user.length >= 3) tokens.add(user.toLowerCase());
  } catch {
    // ignore
  }
  const homeBase = path.basename(os.homedir());
  if (homeBase && homeBase.length >= 3) tokens.add(homeBase.toLowerCase());
  const firstWord = homeBase.split(/[\s'"`]+/)[0];
  if (firstWord && firstWord.length >= 4) tokens.add(firstWord.toLowerCase());
  tokens.add(SERVER_DIR.toLowerCase());
  return [...tokens];
}

function escapeCSharpVerbatim(value) {
  return value.replace(/"/g, '""');
}

function parseCliArgs(argv) {
  let portable = false;
  let outPath = null;
  for (const arg of argv) {
    if (arg === "--portable") {
      portable = true;
    } else if (arg.startsWith("--out=")) {
      outPath = path.resolve(arg.slice("--out=".length));
    }
  }
  return { portable, outPath };
}

async function findCsc() {
  const candidates = [
    "C:\\Windows\\Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe",
    "C:\\Windows\\Microsoft.NET\\Framework\\v4.0.30319\\csc.exe",
  ];
  for (const c of candidates) {
    try {
      const st = await fs.stat(c);
      if (st.isFile()) return c;
    } catch {
      // continue
    }
  }
  throw new Error("csc.exe (.NET Framework 4.x C# compiler) not found.");
}

async function generateBuildConfig(targetPath, portable) {
  const serverDirVal = portable ? "" : escapeCSharpVerbatim(SERVER_DIR);
  const nodeExeVal = portable ? "" : escapeCSharpVerbatim(process.execPath);
  const content = `// Auto-generated by build-exe.mjs at build time.
namespace PurrCamLauncher
{
    internal static class BuildConfig
    {
        public const string DefaultServerDir = @"${serverDirVal}";
        public const string DefaultNodeExe = @"${nodeExeVal}";
    }
}
`;
  await fs.writeFile(targetPath, content, "utf8");
  console.log(
    `[build:exe] Generated ${portable ? "portable (zero-PII)" : "local"} BuildConfig.cs`
  );
}

async function verifyZeroPiiInBinary(filePath) {
  const raw = await fs.readFile(filePath);
  const latin1 = raw.toString("latin1").toLowerCase();
  const utf16 = raw.toString("utf16le").toLowerCase();
  for (const token of getHostLeakTokens()) {
    if (latin1.includes(token) || utf16.includes(token)) {
      throw new Error(
        `Privacy check failed: portable binary ${filePath} contains host-specific path/user token`
      );
    }
  }
}

async function main() {
  const { portable, outPath } = parseCliArgs(process.argv.slice(2));
  const csc = await findCsc();
  console.log(`[build:exe] Using C# compiler: ${csc}`);

  const outputExe =
    outPath ??
    (portable
      ? path.join(PROJECT_ROOT, "release-artifacts", "PurrCam.exe")
      : path.join(PROJECT_ROOT, "PurrCam.exe"));

  await fs.mkdir(path.dirname(outputExe), { recursive: true });

  const buildConfigPath = portable
    ? path.join(os.tmpdir(), `PurrCam-BuildConfig-${process.pid}.cs`)
    : LOCAL_BUILD_CONFIG_CS;

  const refs = [
    "/r:System.dll",
    "/r:System.Core.dll",
    "/r:System.Drawing.dll",
    "/r:System.Windows.Forms.dll",
    "/r:System.Net.Http.dll",
    "/r:System.Web.Extensions.dll",
  ];
  const sources = [CS_SOURCE, buildConfigPath];

  try {
    await generateBuildConfig(buildConfigPath, portable);

    // Pass 1: Generate multi-size (16, 32, 48, 256) cat-eye purrcam.ico
    const tmpHelperExe = path.join(
      os.tmpdir(),
      `purrcam-icogen-${process.pid}.exe`
    );
    try {
      await execFileAsync(csc, [
        "/nologo",
        "/target:exe",
        "/optimize+",
        "/debug-",
        ...refs,
        `/out:${tmpHelperExe}`,
        ...sources,
      ]);
      await execFileAsync(tmpHelperExe, ["--generate-icon", ICO_PATH]);
      const icoStat = await fs.stat(ICO_PATH);
      console.log(
        `[build:exe] Generated multi-size cat-eye icon: ${ICO_PATH} (${icoStat.size} bytes)`
      );
    } finally {
      await fs.unlink(tmpHelperExe).catch(() => {});
    }

    // Pass 2: Compile final standalone PurrCam.exe (/target:winexe + /win32icon + /debug-)
    const { stdout, stderr } = await execFileAsync(csc, [
      "/nologo",
      "/target:winexe",
      "/optimize+",
      "/debug-",
      "/platform:anycpu",
      `/win32icon:${ICO_PATH}`,
      ...refs,
      `/out:${outputExe}`,
      ...sources,
    ]);

    if (stdout.trim()) console.log(stdout.trim());
    if (stderr.trim()) console.error(stderr.trim());

    if (portable) {
      await verifyZeroPiiInBinary(outputExe);
      console.log("[build:exe] Portable zero-PII binary scan PASSED.");
    }

    const exeStat = await fs.stat(outputExe);
    console.log(
      `[build:exe] Built standalone Windows GUI executable: ${outputExe} (${exeStat.size} bytes)`
    );
  } finally {
    if (portable) {
      await fs.unlink(buildConfigPath).catch(() => {});
    }
  }
}

main().catch((err) => {
  console.error("[build:exe] Failed:", err);
  process.exit(1);
});
